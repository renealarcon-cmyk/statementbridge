export const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, es };

export type TranslateParams = Record<string, string | number>;
export type Translate = (key: MessageKey, params?: TranslateParams) => string;

export function interpolate(template: string, params?: TranslateParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

export function translate(lang: Lang, key: MessageKey, params?: TranslateParams): string {
  return interpolate(dictionaries[lang][key], params);
}

export function detectLang(candidate?: string): Lang {
  const value = candidate ?? (typeof navigator !== 'undefined' ? navigator.language : 'en');
  return value.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
}

export const I18nContext = createContext<I18n | null>(null);

export function useI18n(): I18n {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nContext.Provider');
  return context;
}
