#!/usr/bin/env bash
# Build the single-file offline demo of the StatementBridge web app.
#
# Output: apps/web/dist-demo/index.html — ONE self-contained HTML document
# (JS + CSS + wasm engine embedded as base64) that runs when opened directly
# via file://, with a CSP whose connect-src is 'none' (no network, provably).
#
# Requires the wasm package (scripts/build-wasm.sh) and `pnpm install` first.
set -euo pipefail
cd "$(dirname "$0")/.."

WEB=apps/web
WASM="$WEB/src/lib/wasm/pkg/statementbridge_wasm_bg.wasm"
STUB="$WEB/src/lib/wasm-inline.ts"

[[ -f "$WASM" ]] || { echo "wasm package missing — run scripts/build-wasm.sh first" >&2; exit 1; }
[[ -d "$WEB/node_modules" ]] || { echo "run 'pnpm --dir $WEB install' first" >&2; exit 1; }

# Swap the stub for the real embedded binary; restore it whatever happens.
cp "$STUB" "$STUB.orig"
restore() { mv "$STUB.orig" "$STUB"; }
trap restore EXIT

{
  echo "// GENERATED by scripts/build-demo.sh — never commit this file."
  echo "// Embedded statementbridge_wasm_bg.wasm ($(wc -c < "$WASM") bytes)."
  printf "export const WASM_B64 =\n  '"
  base64 -w 0 "$WASM"
  printf "';\n"
} > "$STUB"

VITE_EMBED_WASM=1 pnpm --dir "$WEB" exec vite build

# The inlined document is all we need; drop stray assets copies.
find "$WEB/dist-demo/assets" -type f ! -name "*.html" -delete 2>/dev/null || true
ls -la "$WEB/dist-demo/index.html"
echo "==> single-file demo ready: $WEB/dist-demo/index.html"
